"""Builds pico/helptext.h from Docs/Help.txt and the font in nmirom/nmirom.asm.

Run after editing Docs/Help.txt:   python make_help.py

Help.txt is a list of pages. A line "@@ Title" starts a page; a line starting
with "# " is a heading (shown in yellow). Pages are 32 columns by 22 lines
(rows 1-22 of the screen; row 0 is the title and row 23 the key help).
"""
import os, re, sys

here = os.path.dirname(os.path.abspath(__file__))
help_path = os.path.join(here, '..', 'Docs', 'Help.txt')
asm_path = os.path.join(here, '..', 'nmirom', 'nmirom.asm')
out_path = os.path.join(here, 'helptext.h')

COLS, ROWS = 32, 22

pages = []
for ln in open(help_path, encoding='ascii').read().replace('\r', '').split('\n'):
    if ln.startswith('@@ '):
        pages.append((ln[3:].rstrip(), []))
    elif pages:
        pages[-1][1].append(ln.rstrip())
errors = []
for title, lines in pages:
    while lines and lines[-1] == '':
        lines.pop()
    if len(title) > 26:
        errors.append('title too long: %r' % title)
    if len(lines) > ROWS:
        errors.append('%r has %d lines (max %d)' % (title, len(lines), ROWS))
    for l in lines:
        shown = l[2:] if l.startswith('# ') else l
        if '{' in shown:
            # {tokens} are filled in by the pico (help_token in picoface.cxx): check the rest
            if not re.fullmatch(r'\{(version|flash|sd|error1|error2)\}', shown):
                errors.append('%r: unknown token in %r' % (title, l))
            continue
        if len(shown) > COLS:
            errors.append('%r: line too long (%d): %r' % (title, len(shown), l))
        for ch in shown:
            if not 32 <= ord(ch) < 127:
                errors.append('%r: character %r not in the font' % (title, ch))
if not pages:
    errors.append('no pages')
if len(pages) > 40:
    errors.append('too many pages')
if errors:
    print('\n'.join(errors), file=sys.stderr)
    sys.exit(1)

# the font: the 96 characters (space to DEL) after "charbank:" in nmirom.asm
font = []
inside = False
for ln in open(asm_path, encoding='utf-8', errors='replace'):
    if ln.startswith('charbank:'):
        inside = True
        continue
    if inside:
        m = re.match(r'\s*defb\s+((?:0x[0-9a-fA-F]{2},?){8})', ln)
        if m:
            font.append([int(x, 16) for x in m.group(1).split(',')])
            if len(font) == 96:
                break
if len(font) != 96:
    print('could not read the font from nmirom.asm (got %d)' % len(font), file=sys.stderr)
    sys.exit(1)

def cstr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'

with open(out_path, 'w', newline='\n') as f:
    f.write('// Generated by make_help.py from Docs/Help.txt and nmirom.asm. Do not edit.\n')
    f.write('// Part of PicoMenu (GNU GPL v3 or later, see LICENSE). The font is Unscii 8 by Viznut,\n')
    f.write('// public domain / CC0 (see THIRD-PARTY-NOTICES.txt).\n')
    f.write('#pragma once\n#include <stdint.h>\n\n')
    f.write('static const uint8_t help_font[96][8] = {\n')
    for g in font:
        f.write('    {' + ', '.join('0x%02x' % b for b in g) + '},\n')
    f.write('};\n\n')
    f.write('struct HelpPage { const char* title; const char* text; };\n')
    f.write('static const HelpPage help_pages[] = {\n')
    for title, lines in pages:
        f.write('    { %s,\n' % cstr(title))
        for i, l in enumerate(lines):
            f.write('      %s\n' % cstr(l + '\n'))
        f.write('    },\n')
    f.write('};\n')
    f.write('static const int HELP_PAGE_COUNT = %d;\n' % len(pages))
print('%d pages' % len(pages))
