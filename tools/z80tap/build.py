# Assembles loader.asm (sjasmplus) twice, the loader at ORG 0 and 0x1000 and its stub at DISP 0
# and 0x2000, to find the bytes that are addresses (to move with the loader, or with the stub),
# and writes pico/z80tap_loader.h: the bytes, those places, and where each value goes.
# Run it from anywhere: python3 tools/z80tap/build.py
import os, subprocess, sys, tempfile
here = os.path.dirname(os.path.abspath(__file__))
out_h = os.path.join(here, '..', '..', 'pico', 'z80tap_loader.h')

def assemble(org, disp):
    d = tempfile.mkdtemp()
    sym = os.path.join(d, 'l.sym')
    subprocess.run(['sjasmplus', '--nologo', '-DLC_ORG=%d' % org, '-DSTUB_DISP=%d' % disp, '--sym=' + sym,
                    os.path.join(here, 'loader.asm')], cwd=d, check=True, stdout=subprocess.DEVNULL)
    data = open(os.path.join(d, 'loader.bin'), 'rb').read()
    syms = {}
    for ln in open(sym):
        if ': EQU' in ln:
            k, v = ln.split(': EQU')
            syms[k.strip()] = int(v.strip(), 16)
    return data, syms

a, sa = assemble(0, 0)
b, sb = assemble(0x1000, 0x2000)
assert len(a) == len(b)
reloc_lc, reloc_stub = [], []
# the moves are whole multiples of 256, so only an address's high byte differs
for i in range(len(a)):
    if a[i] != b[i]:
        d = (b[i] - a[i]) & 0xFF
        if d == 0x10:
            reloc_lc.append(i - 1)
        elif d == 0x20:
            reloc_stub.append(i - 1)
        else:
            sys.exit('byte %d moved by %x' % (i, d))
stub = sa['stub_image']
fields = ['table', 'ayflag', 'aysel', 'ayregs', 'page_stub', 'stub_at', 'stub_image']
sfields = ['s_page', 's_i', 's_im', 's_af2', 's_bc2', 's_de2', 's_hl2', 's_ix', 's_iy', 's_border', 's_r',
           's_bc', 's_de', 's_hl', 's_af', 's_sp', 's_ei', 's_pc']
with open(out_h, 'w') as f:
    f.write('// Generated by tools/z80tap/build.py from tools/z80tap/loader.asm. Do not edit.\n')
    f.write('// Part of PicoMenu (GNU GPL v3 or later).\n#pragma once\n#include <stdint.h>\n\n')
    f.write('namespace z80tap {\n')
    f.write('static const uint8_t LOADER[%d] = {' % len(a))
    for k, v in enumerate(a):
        if k % 16 == 0:
            f.write('\n    ')
        f.write('0x%02x, ' % v)
    f.write('\n};\n')
    f.write('static const uint16_t LOADER_SIZE = %d;      // up to the table\n' % len(a))
    f.write('static const uint16_t LC_SIZE = %d;          // the room it has (the last block)\n' % sa['LC_SIZE'])
    f.write('static const uint16_t STUB_SIZE = %d;\n' % sa['STUB_SIZE'])
    f.write('// 16-bit addresses within the loader: + its address; within the stub: + the stub\'s\n')
    f.write('static const uint16_t RELOC_LC[] = { %s };\n' % ', '.join(map(str, reloc_lc)))
    f.write('static const uint16_t RELOC_STUB[] = { %s };\n' % ', '.join(map(str, reloc_stub)))
    for k in fields:
        f.write('static const uint16_t AT_%s = %d;\n' % (k.upper(), sa[k]))
    f.write('// in the stub (from its start)\n')
    for k in sfields:
        f.write('static const uint16_t S_%s = %d;\n' % (k[2:].upper(), sa[k] - 0))
    f.write('}   // namespace z80tap\n')
print('loader %d bytes, stub %d, %d + %d places to move' % (len(a), sa['STUB_SIZE'], len(reloc_lc), len(reloc_stub)))
